const GG52_LANG_TAGS = { en: "en", pt: "pt-BR", es: "es" };
const GG52_LANG_STORAGE_KEY = "gg52-lang";

const GG52_I18N = {
  current: "pt",

  t(key) {
    const table = GG52_TRANSLATIONS[this.current] || {};
    return table[key] || GG52_TRANSLATIONS.en[key] || "";
  },

  apply() {
    document.documentElement.lang = GG52_LANG_TAGS[this.current] || "en";

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const value = this.t(el.getAttribute("data-i18n"));
      if (value) {
        el.innerHTML = value;
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const value = this.t(el.getAttribute("data-i18n-placeholder"));
      if (value) {
        el.setAttribute("placeholder", value);
      }
    });

    document.querySelectorAll(".lang-btn").forEach((btn) => {
      const isActive = btn.dataset.lang === this.current;
      btn.classList.toggle("is-active", isActive);
      btn.setAttribute("aria-pressed", isActive ? "true" : "false");
    });
  },

  set(lang) {
    if (!GG52_TRANSLATIONS[lang]) {
      return;
    }

    this.current = lang;
    try {
      localStorage.setItem(GG52_LANG_STORAGE_KEY, lang);
    } catch (_error) {
      // localStorage indisponivel (ex: modo privado); segue sem persistir.
    }
    this.apply();
  },
};

(function initI18n() {
  try {
    const saved = localStorage.getItem(GG52_LANG_STORAGE_KEY);
    if (saved && GG52_TRANSLATIONS[saved]) {
      GG52_I18N.current = saved;
    }
  } catch (_error) {
    // Sem localStorage, permanece no idioma padrao.
  }

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => GG52_I18N.set(btn.dataset.lang));
  });

  GG52_I18N.apply();
})();
